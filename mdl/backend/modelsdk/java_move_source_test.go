package modelsdkbackend

import (
	"os"
	"path/filepath"
	"strings"
	"testing"
)

// A cross-module MOVE of a Java or JavaScript action must take its source file
// along: mxbuild looks for it under the new module's directory and generates a
// stub that throws when it finds nothing there (measured on 11.13.0; see
// sdk/javaactions/move_test.go).

func writeFile(t *testing.T, path, content string) {
	t.Helper()
	if err := os.MkdirAll(filepath.Dir(path), 0o755); err != nil {
		t.Fatal(err)
	}
	if err := os.WriteFile(path, []byte(content), 0o644); err != nil {
		t.Fatal(err)
	}
}

func TestMoveJavaSourceFileTakesTheCodeAlong(t *testing.T) {
	root := t.TempDir()
	from := filepath.Join(root, "javasource", "jama", "actions", "JA_Hello.java")
	writeFile(t, from, "package jama.actions;\r\n\r\npublic class JA_Hello {\r\n\t// BEGIN USER CODE\r\n\treturn \"jama.actions\";\r\n\t// END USER CODE\r\n}\r\n")

	b := &Backend{path: filepath.Join(root, "App.mpr")}
	moved, err := b.MoveJavaSourceFile("JamA", "JamB", "JA_Hello")
	if err != nil {
		t.Fatal(err)
	}
	if moved != "javasource/jamb/actions/JA_Hello.java" {
		t.Errorf("reported %q, want the project-relative destination", moved)
	}
	if _, err := os.Stat(from); !os.IsNotExist(err) {
		t.Errorf("the source is still under the old module (stat err %v)", err)
	}
	got, err := os.ReadFile(filepath.Join(root, "javasource", "jamb", "actions", "JA_Hello.java"))
	if err != nil {
		t.Fatal(err)
	}
	if !strings.HasPrefix(string(got), "package jamb.actions;\r\n") {
		t.Errorf("package line not rewritten:\n%s", got)
	}
	if !strings.Contains(string(got), "return \"jama.actions\";") {
		t.Errorf("the user code was rewritten:\n%s", got)
	}
}

// The destination already holding a file is refused before anything moves: it
// is the author's code too, and nothing says which of the two is wanted.
func TestMoveJavaSourceFileRefusesAnOccupiedDestination(t *testing.T) {
	root := t.TempDir()
	from := filepath.Join(root, "javasource", "jama", "actions", "JA_Hello.java")
	to := filepath.Join(root, "javasource", "jamb", "actions", "JA_Hello.java")
	writeFile(t, from, "package jama.actions; // A\n")
	writeFile(t, to, "package jamb.actions; // B\n")

	b := &Backend{path: filepath.Join(root, "App.mpr")}
	if _, err := b.MoveJavaSourceFile("JamA", "JamB", "JA_Hello"); err == nil || !strings.Contains(err.Error(), "already exists") {
		t.Fatalf("want an already-exists refusal, got %v", err)
	}
	for path, want := range map[string]string{from: "// A", to: "// B"} {
		got, err := os.ReadFile(path)
		if err != nil || !strings.Contains(string(got), want) {
			t.Errorf("%s changed (err %v): %q", path, err, got)
		}
	}
}

// An action with no source on disk yet has nothing to move.
func TestMoveJavaSourceFileWithoutSource(t *testing.T) {
	b := &Backend{path: filepath.Join(t.TempDir(), "App.mpr")}
	moved, err := b.MoveJavaSourceFile("JamA", "JamB", "JA_Hello")
	if err != nil || moved != "" {
		t.Errorf("got (%q, %v), want nothing moved and no error", moved, err)
	}
}

func TestMoveJavaScriptSourceFileTakesTheCodeAlong(t *testing.T) {
	root := t.TempDir()
	from := filepath.Join(root, "javascriptsource", "jama", "actions", "JSA_Hello.js")
	const src = "// This file was generated by Mendix Studio Pro.\nexport async function JSA_Hello() {\n\t// BEGIN USER CODE\n\treturn 1;\n\t// END USER CODE\n}\n"
	writeFile(t, from, src)

	b := &Backend{path: filepath.Join(root, "App.mpr")}
	moved, err := b.MoveJavaScriptSourceFile("JamA", "JamB", "JSA_Hello")
	if err != nil {
		t.Fatal(err)
	}
	if moved != "javascriptsource/jamb/actions/JSA_Hello.js" {
		t.Errorf("reported %q", moved)
	}
	got, err := os.ReadFile(filepath.Join(root, "javascriptsource", "jamb", "actions", "JSA_Hello.js"))
	if err != nil || string(got) != src {
		t.Errorf("the source did not arrive unchanged (err %v): %q", err, got)
	}
	if _, err := os.Stat(from); !os.IsNotExist(err) {
		t.Errorf("the source is still under the old module (stat err %v)", err)
	}
}

// The move is one of the files beside the model a statement touched, so exec
// names it with the rest (ako/mxcli#1618): as a move, from the old path.
func TestMoveJavaSourceFileIsReported(t *testing.T) {
	root := t.TempDir()
	writeFile(t, filepath.Join(root, "javasource", "jama", "actions", "JA_Hello.java"), "package jama.actions;\n")

	b := &Backend{path: filepath.Join(root, "App.mpr")}
	if _, err := b.MoveJavaSourceFile("JamA", "JamB", "JA_Hello"); err != nil {
		t.Fatal(err)
	}
	changes := b.TakeSourceFileChanges()
	if len(changes) != 1 || changes[0].Path != "javasource/jamb/actions/JA_Hello.java" ||
		changes[0].From != "javasource/jama/actions/JA_Hello.java" || changes[0].Removed {
		t.Errorf("reported %+v, want one move jama -> jamb", changes)
	}
}
