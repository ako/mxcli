// GlyphIcon is one entry of the Mendix glyph font: the numeric character code
// `icon glyph <n>` stores, and the name it is known by.
type GlyphIcon struct {
	// Code is the character code, which is what the model stores. This is the
	// whole identity of a glyph icon — Forms$GlyphIcon holds no name.
	Code int
	// Name is the icon's name without the `glyphicon-` prefix.
	Name string
	// Aliases are further names for the same code (only `bitcoin` has any).
	Aliases []string
}

