// GlyphIcons returns every glyph the Mendix font defines, ordered by code.
func GlyphIcons() []GlyphIcon { return glyphIcons }

// LookupGlyph returns the icon for a character code.
func LookupGlyph(code int) (GlyphIcon, bool) {
	i := sort.Search(len(glyphIcons), func(i int) bool { return glyphIcons[i].Code >= code })
	if i < len(glyphIcons) && glyphIcons[i].Code == code {
		return glyphIcons[i], true
	}
	return GlyphIcon{}, false
}

// glyphCodeDefined reports whether the Mendix glyph font defines this code.
func glyphCodeDefined(code int) bool {
	_, ok := LookupGlyph(code)
	return ok
}
